"""The README's picture: one week, two repairs, drawn from a committed case.

    uv run python -m benchmarks.figure            # report what it would draw
    uv run python -m benchmarks.figure --write    # and write the SVG

`benchmarks.md` argues the headline claim in four numbers and `README.md` repeats them.
This draws it instead, because a roster is a grid of people against days and every reader
of those tables has been reconstructing that grid in their head.

## Why a benchmark case and not the demo scenario

The obvious source is `scenarios/saturday_sick_call.json`, which `quickstart.md` already
walks through. It cannot carry this figure: at `now = 129` the whole week before Saturday
morning is pinned by `R-PIN-PAST`, so a cold cost re-solve has almost nothing left it is
allowed to move and returns **the same single change** the replan does. That is a true
fact about late notice and a useless picture of the objective.

So the figure is drawn from `headline/1` — the same Saturday 09:00 sick call, one seed
over, where enough of Sunday is still movable for the two objectives to disagree. It is
seeded, committed to `manifest.json`, and regenerated by the command above rather than
drawn by hand (`D-148`).

**The numbers on the figure are one case, not the set.** Six changes against two, where
the set-wide means in `benchmarks.md` are 12.4 and 2.4. A single case cannot show a mean
and this one does not claim to; what it shows is the shape of the difference, which is the
part a table hides.

## What the drawing commits to

Every cell is a `(employee, day, shift)` triple, so the grid is the decision variable
`x[e, d, s]` and nothing is aggregated away. Three states are drawn -- held, added,
dropped -- and the vertical rule marks `now`, left of which `R-PIN-PAST` makes the roster
immutable. A reader who counts the marked cells gets the `changes` column exactly.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

from roster_replan.domain import Instance, Roster

from .methods import COLD_COST, WARM_REPLAN, run
from .suite import build

CASE = "headline/1"
OUT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "saturday-sick-call.svg"

# Mid-tone throughout, so every mark reads against a light or a dark page without relying
# on a media query the host may strip. The `prefers-color-scheme` block below only lifts
# the text, which is the one element a mid-tone genuinely fails for.
INK = "#4a5560"
FAINT = "#c6cdd5"
HELD = "#8c959f"
ADDED = "#1a7f37"
DROPPED = "#cf222e"

CELL_W, CELL_H, GAP = 20, 15, 6
LABEL_W = 42
PANEL_PAD = 34


def _states(instance: Instance, incumbent: Roster, roster: Roster) -> dict:
    """One state per drawn cell. Absent from the map means nobody worked it."""
    states = {}
    for key in incumbent | roster:
        if key in incumbent and key in roster:
            states[key] = "held"
        elif key in roster:
            states[key] = "added"
        else:
            states[key] = "dropped"
    return states


def _x(day: int, shift: int, shifts: int) -> float:
    return LABEL_W + day * (shifts * CELL_W + GAP) + shift * CELL_W


def _panel(instance, incumbent, roster, *, title, note, top) -> list[str]:
    shifts = len(instance.shift_types)
    states = _states(instance, incumbent, roster)
    out = [
        f'<text x="0" y="{top - 16}" class="h">{title}</text>',
        f'<text x="0" y="{top - 3}" class="n">{note}</text>',
    ]

    grid_top = top + 12
    for day in range(instance.days):
        label = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"][day % 7]
        cx = _x(day, 0, shifts) + shifts * CELL_W / 2
        out.append(f'<text x="{cx:.0f}" y="{grid_top - 3}" class="d">{label}</text>')

    for row, employee in enumerate(instance.employees):
        y = grid_top + row * CELL_H
        out.append(
            f'<text x="{LABEL_W - 8}" y="{y + CELL_H - 4:.0f}" class="e">{employee.name}</text>'
        )
        for day in range(instance.days):
            for shift in range(shifts):
                x = _x(day, shift, shifts)
                state = states.get((row, day, shift))
                cls = {"held": "held", "added": "add", "dropped": "drop"}.get(state, "off")
                out.append(
                    f'<rect x="{x:.0f}" y="{y:.0f}" width="{CELL_W - 2}" '
                    f'height="{CELL_H - 2}" rx="2" class="{cls}"/>'
                )

    # `now`: the boundary R-PIN-PAST freezes behind. A slot is past when it has started.
    boundary = None
    for day in range(instance.days):
        for shift in range(shifts):
            start = day * 24 + instance.shift_types[shift].start_hour
            if start >= instance.now:
                boundary = boundary or _x(day, shift, shifts) - GAP / 2
    height = len(instance.employees) * CELL_H
    if boundary is not None:
        out.append(
            f'<line x1="{boundary:.0f}" y1="{grid_top - 12}" x2="{boundary:.0f}" '
            f'y2="{grid_top + height:.0f}" class="now"/>'
        )
    return out


def render(case: str = CASE) -> str:
    """The SVG, as text. Deterministic: the case is seeded and the solves carry a seed."""
    scenario = build(case)
    instance, incumbent = scenario.instance, scenario.incumbent
    cold = run(COLD_COST, scenario, seed=7, time_limit=30.0)
    warm = run(WARM_REPLAN, scenario, seed=7, time_limit=30.0)

    shifts = len(instance.shift_types)
    width = LABEL_W + instance.days * (shifts * CELL_W + GAP)
    panel_h = len(instance.employees) * CELL_H + PANEL_PAD + 12
    height = 2 * panel_h + 34

    body: list[str] = []
    body += _panel(
        instance,
        incumbent,
        cold.roster_or_fail(),
        title="Cold re-solve, cost objective",
        note=f"{cold.changes} assignments moved — three of them nobody had asked about",
        top=PANEL_PAD,
    )
    body += _panel(
        instance,
        incumbent,
        warm.roster_or_fail(),
        title="Minimum-disruption replan",
        note=f"{warm.changes} assignments moved — the absence, and its one replacement",
        top=PANEL_PAD + panel_h,
    )

    legend_y = height - 8
    legend = [
        f'<rect x="0" y="{legend_y - 9}" width="10" height="10" rx="2" class="held"/>',
        f'<text x="15" y="{legend_y}" class="n">held</text>',
        f'<rect x="52" y="{legend_y - 9}" width="10" height="10" rx="2" class="add"/>',
        f'<text x="67" y="{legend_y}" class="n">added</text>',
        f'<rect x="112" y="{legend_y - 9}" width="10" height="10" rx="2" class="drop"/>',
        f'<text x="127" y="{legend_y}" class="n">dropped</text>',
        f'<line x1="188" y1="{legend_y - 9}" x2="188" y2="{legend_y + 1}" class="now"/>',
        f'<text x="194" y="{legend_y}" class="n">now — pinned past to its left</text>',
    ]

    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
            f'width="{width}" height="{height}" font-family="ui-sans-serif,system-ui,sans-serif">',
            "<style>",
            f".h{{font-size:12px;font-weight:600;fill:{INK}}}",
            f".n{{font-size:9.5px;fill:{INK}}}",
            f".d{{font-size:8.5px;fill:{INK};text-anchor:middle}}",
            f".e{{font-size:8.5px;fill:{INK};text-anchor:end}}",
            f".off{{fill:{FAINT};fill-opacity:.45}}",
            f".held{{fill:{HELD}}}",
            f".add{{fill:{ADDED}}}",
            f".drop{{fill:none;stroke:{DROPPED};stroke-width:1.5}}",
            f".now{{stroke:{DROPPED};stroke-width:1;stroke-dasharray:2 2}}",
            "@media (prefers-color-scheme:dark){",
            ".h,.n,.d,.e{fill:#a3adb8}.off{fill:#30363d;fill-opacity:.85}",
            ".held{fill:#9198a1}.add{fill:#2ea043}",
            "}",
            "</style>",
            *body,
            *legend,
            "</svg>",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help=f"write {OUT.name}")
    args = parser.parse_args(argv)

    svg = render()
    if args.write:
        OUT.write_text(svg)
        print(f"wrote {OUT.relative_to(OUT.parents[1])} ({len(svg)} bytes)")
    else:
        print(f"{CASE}: {len(svg)} bytes, not written. Pass --write.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
